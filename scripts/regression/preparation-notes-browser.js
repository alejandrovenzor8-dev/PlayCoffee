async page => {
  const origin = 'http://127.0.0.1:3059';
  const context = page.context();
  const product = { id: 'eggs', name: 'Huevos estrellados', price: 100, preparationStation: 'KITCHEN', isActive: true, modifiers: [] };
  let items = [];
  const submissions = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const order = () => ({ id: 'sale', orderNumber: 'PC-HUEVOS', status: 'PENDING', tableId: 'table-2', total: items.reduce((sum, i) => sum + i.quantity * 100, 0), items, payments: [], createdAt: '2026-11-01T15:00:00Z' });
  const table = () => ({ id: 'table-2', areaId: 'area', number: '2', status: 'OCCUPIED', capacity: 4, posX: 20, posY: 20, width: 150, height: 130, shape: 'rect', isActive: true, area: { id: 'area', name: 'Terraza' }, orders: [order()] });
  await context.addInitScript(() => localStorage.setItem('playcoffee-auth', JSON.stringify({ version: 0, state: { user: { id: 'qa-user', branchId: 'qa', firstName: 'QA', lastName: 'Cashier', role: 'CASHIER', isActive: true }, accessToken: 'fixture', refreshToken: 'fixture', isAuthenticated: true } })));
  await context.routeWebSocket('**', socket => socket.close());
  await context.route('**/*', async route => {
    const url = route.request().url();
    const path = url.replace(/^https?:\/\/[^/]+/, '').split('?')[0];
    const headers = { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': 'GET, POST, OPTIONS' };
    const respond = data => route.fulfill({ status: 200, contentType: 'application/json', headers, body: JSON.stringify({ data }) });
    if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers });
    if (url.startsWith(origin + '/') && !path.includes('/api/v1/') && path !== '/health') return path.includes('sw.js') ? route.abort() : route.continue();
    if (path === '/health') return route.fulfill({ status: 200, body: '{}' });
    if (path.endsWith('/print/cashier-policy')) return respond({ cashierMode: 'BUSINESS_ONLY', autoCustomer: false, confirmClose: false, allowReprint: true });
    if (path.endsWith('/products/categories')) return respond([]);
    if (path.endsWith('/products')) return respond([product]);
    if (path.endsWith('/tables/areas')) return respond([{ id: 'area', branchId: 'qa', name: 'Terraza', isActive: true, _count: { tables: 1 }, tables: [table()] }]);
    if (path.endsWith('/tables')) return respond([table()]);
    if (path.endsWith('/payments/config')) return respond({ tipEnabled: false, defaultTipPercentage: 0, tipPercentages: [0] });
    if (path.endsWith('/orders/sale')) return respond(order());
    if (path.endsWith('/orders/sale/items')) {
      const data = route.request().postDataJSON(); submissions.push(data);
      items = data.items.map((i, index) => ({ ...i, id: 'line-' + index, product, totalPrice: i.quantity * 100, unitPrice: 100, modifiers: [], status: 'PENDING' }));
      return respond(order());
    }
    if (path.endsWith('/payments/order/sale')) return respond({ payments: [], summary: { orderId: 'sale', total: order().total, totalPaid: 0, remainingAmount: order().total, paymentStatus: 'UNPAID', changeAmount: 0 } });
    if (path.endsWith('/cash/closing-reminder')) return respond(null);
    if (path.includes('/api/v1/')) throw new Error('Unexpected API request: ' + path);
    if (url.startsWith(origin + '/') && !path.includes('sw.js')) return route.continue();
    return route.abort();
  });
  await page.goto(origin + '/pos?orderId=sale');
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('button').filter({ hasText: 'Huevos estrellados' }).click();
  await page.getByRole('button').filter({ hasText: 'Huevos estrellados' }).click();
  await page.getByRole('button', { name: 'Separar 1', exact: true }).click();
  let notes = page.getByLabel('Notas de Huevos estrellados');
  assert(await notes.count() === 2, 'split must create two independent servings');
  await notes.nth(0).fill('Bien cocidos\nSin cebolla');
  await notes.nth(1).fill('Tiernitos');
  await page.getByRole('button').filter({ hasText: 'Huevos estrellados' }).click();
  notes = page.getByLabel('Notas de Huevos estrellados');
  assert(await notes.count() === 3, 'adding another product must not merge an annotated serving');
  assert(await notes.nth(0).inputValue() === 'Bien cocidos\nSin cebolla' && await notes.nth(1).inputValue() === 'Tiernitos', 'preparation comments were overwritten');
  await notes.nth(2).fill('Sin sal');
  await page.getByRole('button', { name: 'Agregar al ticket', exact: true }).click();
  await page.getByText('Producto agregado. Recuerda enviar/imprimir comanda si aplica.', { exact: true }).waitFor();
  assert(submissions[0].items.length === 3 && submissions[0].items.every(i => i.quantity === 1), 'split changed quantities');
  assert(submissions[0].items.map(i => i.notes).join('|') === 'Bien cocidos\nSin cebolla|Tiernitos|Sin sal', 'POS submission lost comments');
  items = [];
  await page.goto(origin + '/tables');
  await page.getByRole('button').filter({ hasText: 'OCUPADA' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button').filter({ hasText: 'Huevos estrellados' }).click();
  await page.getByLabel('Notas de Huevos estrellados').fill('Bien cocidos');
  await dialog.getByRole('button').filter({ hasText: 'Huevos estrellados' }).click();
  notes = page.getByLabel('Notas de Huevos estrellados');
  assert(await notes.count() === 2, 'Mesas merged different preparation variants');
  await notes.nth(1).fill('Tiernitos');
  await dialog.getByRole('button', { name: 'Agregar al ticket', exact: true }).click();
  await page.getByText('Preparación: Bien cocidos', { exact: true }).waitFor();
  await page.getByText('Preparación: Tiernitos', { exact: true }).waitFor();
  assert(submissions[1].items.length === 2 && submissions[1].items.every(i => i.quantity === 1), 'Mesas quantities changed');
  assert(submissions[1].items.map(i => i.notes).join('|') === 'Bien cocidos|Tiernitos', 'Mesas lost comments');
  await page.screenshot({ path: 'build/preparation-notes-mesas.png', fullPage: true });
  return { passed: ['POS split preserves portions', 'annotated products remain separate when added again', 'Mesas saves independent preparation comments', 'saved comments visible on ticket'], fixtureApi: true };
}
